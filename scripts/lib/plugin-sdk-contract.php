<?php

declare(strict_types=1);

/**
 * packages/plugin-sdk/src/contract.generated.ts, rendered from the PHP SDK
 * (SDK 1.165, decision D8): the block contract (every block type, whether it is
 * a container, its child slots and its props with their kind, whether they are
 * required and their allowed values), the tree limits, and the SDK version the
 * package moves in lockstep with.
 *
 * Shared by scripts/plugin-sdk-contract.php and tests/Sdk/PluginSdkPackageTest.php
 * so the two can't render it differently.
 */

const WHITY_PLUGIN_SDK_CONTRACT_FILE = 'packages/plugin-sdk/src/contract.generated.ts';

function whity_plugin_sdk_contract_render(): string
{
    $contract = \Whity\Sdk\Frontend\Blocks\BlockContract::class;
    $json = static fn (mixed $value): string => (string) json_encode($value, JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR);

    $out = "// Generated by `php scripts/plugin-sdk-contract.php` from the PHP SDK. Do not edit by hand:\n"
        . "// tests/Sdk/PluginSdkPackageTest.php fails when this file is not what the script writes.\n\n"
        . "/** The PHP SDK version this package matches (Whity\\Sdk\\Sdk::VERSION). */\n"
        . 'export const SDK_VERSION = ' . $json(\Whity\Sdk\Sdk::VERSION) . ";\n\n"
        . "/** The deepest a block tree may nest (BlockContract::MAX_DEPTH). */\n"
        . 'export const MAX_DEPTH = ' . $contract::MAX_DEPTH . ";\n\n"
        . "/** The most nodes a block tree may hold (BlockContract::MAX_NODES). */\n"
        . 'export const MAX_NODES = ' . $contract::MAX_NODES . ";\n\n"
        . "/** The most nodes a `flow` block may draw (BlockContract::FLOW_MAX_NODES). */\n"
        . 'export const FLOW_MAX_NODES = ' . $contract::FLOW_MAX_NODES . ";\n\n"
        . "/**\n * Every block type the host accepts, in the contract's order: whether it is a\n"
        . " * container, the child slots it carries, and each prop's kind, whether it is\n"
        . " * required and (for enum and intEnum) its allowed values.\n */\n"
        . "export const BLOCK_CONTRACT = {\n";

    foreach ($contract::rules() as $type => $rule) {
        $slots = $contract::childSlots($type);
        $out .= '  ' . $json($type) . ": {\n"
            . '    container: ' . ($rule['container'] ? 'true' : 'false') . ",\n"
            . '    slots: ' . $json($slots) . ",\n"
            . "    props: {\n";
        foreach ($rule['props'] as $prop => $propRule) {
            $out .= '      ' . $json($prop) . ': { kind: ' . $json($propRule['type'])
                . ', required: ' . ($propRule['required'] ? 'true' : 'false')
                . (isset($propRule['values']) ? ', values: ' . $json($propRule['values']) : '')
                . " },\n";
        }
        $out .= "    },\n  },\n";
    }

    return $out . "} as const;\n\n"
        . "/** A block type name. */\n"
        . "export type BlockType = keyof typeof BLOCK_CONTRACT;\n\n"
        . "/** Every block type name, in the contract's order. */\n"
        . "export const BLOCK_TYPES = Object.keys(BLOCK_CONTRACT) as BlockType[];\n";
}
