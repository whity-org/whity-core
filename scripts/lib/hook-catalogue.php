<?php

declare(strict_types=1);

/**
 * The event tables of docs/wiki/HOOK_SYSTEM.md, rendered from
 * Whity\Sdk\Hooks\EventCatalogue (SDK 1.164). Shared by
 * scripts/hook-catalogue.php and tests/Sdk/EventCatalogueTest.php so the two
 * can't render it differently.
 */

const WHITY_HOOK_CATALOGUE_START = '<!-- event-catalogue:start (generated by php scripts/hook-catalogue.php from Whity\Sdk\Hooks\EventCatalogue; do not edit by hand) -->';
const WHITY_HOOK_CATALOGUE_END = '<!-- event-catalogue:end -->';

/** The generated tables, one per group, in the catalogue's order. */
function whity_hook_catalogue_render(): string
{
    $constants = array_flip(array_filter((new ReflectionClass(\Whity\Sdk\Hooks\Events::class))->getConstants(), 'is_string'));

    $groups = [];
    foreach (\Whity\Sdk\Hooks\EventCatalogue::all() as $name => $info) {
        $groups[$info->group][] = $info;
    }

    $out = '';
    foreach ($groups as $group => $events) {
        $out .= "### {$group}\n\n| Event | Constant | Kind | Since | Payload | Notes |\n| --- | --- | --- | --- | --- | --- |\n";
        foreach ($events as $info) {
            $kind = $info->kind . ($info->vetoable && $info->kind !== \Whity\Sdk\Hooks\EventCatalogue::VETO ? ', veto' : '');
            $payload = implode(', ', array_map(static fn (string $key): string => "`{$key}`", $info->payload));
            $notes = str_replace('|', '\|', ($info->renamedFrom !== null ? "Was `{$info->renamedFrom}`. " : '') . $info->notes);
            $out .= sprintf(
                "| `%s` | `%s` | %s | %s | %s | %s |\n",
                $info->name,
                $constants[$info->name] ?? '?',
                $kind,
                $info->since,
                $payload,
                $notes,
            );
        }
        $out .= "\n";
    }

    return rtrim($out) . "\n";
}

/**
 * The page with its generated region replaced.
 *
 * @throws RuntimeException when the page has no markers
 */
function whity_hook_catalogue_apply(string $page): string
{
    $page = str_replace("\r\n", "\n", $page);
    $start = strpos($page, WHITY_HOOK_CATALOGUE_START);
    $end = strpos($page, WHITY_HOOK_CATALOGUE_END);
    if ($start === false || $end === false || $end < $start) {
        throw new RuntimeException('docs/wiki/HOOK_SYSTEM.md has no event-catalogue markers');
    }

    return substr($page, 0, $start) . WHITY_HOOK_CATALOGUE_START . "\n\n" . whity_hook_catalogue_render() . "\n" . substr($page, $end);
}
